#!/bin/bash

# Generate analysis flags and messages
# to be used in conjunction with Error.c and Error.h
# searches the sources for comment lines following the pattern:
# // IVFLAGWARN <FLAGNAME> <NUMBER> "<message string>"   (a warning)
# // IVFLAGERR  <FLAGNAME> <NUMBER> "<message string>"   (an error)
#
# NUMBER is the flag number (1-32); the flag code is 1<<(NUMBER-1). Numbers
# are part of the library interface: never renumber an existing flag, give a
# new flag the next free number. Numbers must be unique and without gaps.
#
# it generates the macro FLAGNAME and the flag masks in ivanalyzeflags.h,
# and the message, name and error tables in ivanalyzemessages.h
# ivanalyzeflags.h should be included in all sources that raise flags,
# ivanalyzemessages.h is a private include for Error.c
FILE1="ivanalyzeflags.h"
FILE2="ivanalyzemessages.h"
if [ -z "$1" ]
then
	echo gen_ivanalyzeflags.sh needs arguments!
	exit 1
fi
srcdir="$1"
shift
for s in $@
do
	echo Collecting flags from $s
done

TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT
for s in $@
do
	grep -hEo '//IVFLAG(WARN|ERR)[[:space:]].*' "$srcdir/$s"
done | sort -u > "$TMP"

# validate and write both headers in one go
awk -v F1="$FILE1" -v F2="$FILE2" '
function fail(msg) { print "gen_ivanalyzeflags.sh: " msg > "/dev/stderr"; bad=1; exit 1 }
{
	kind=$1; name=$2; num=$3
	if (num !~ /^[0-9]+$/) fail("flag " name " has no number")
	num=num+0
	if (num<1 || num>32) fail("flag " name " has number " num " outside 1-32")
	if (num in byname) fail("flag number " num " used by " byname[num] " and " name)
	if (name in seen) fail("flag " name " defined twice")
	msg=$0; sub(/^[^"]*/, "", msg)
	if (msg !~ /^".*"$/) fail("flag " name " has no quoted message")
	seen[name]=1; byname[num]=name; message[num]=msg
	iserr[num]=(kind=="//IVFLAGERR")
	if (num>max) max=num
}
END {
	if (bad) exit 1
	for (i=1;i<=max;i++) if (!(i in byname)) fail("flag number " i " is unused (numbers must be contiguous)")
	errmask=0; warnmask=0
	for (i=1;i<=max;i++) { if (iserr[i]) errmask+=2^(i-1); else warnmask+=2^(i-1) }

	print "/* File generated by gen_ivanalyzeflags.sh, do not edit by hand */" > F1
	print "#define FLAG_NOFLAG 0" > F1
	for (i=1;i<=max;i++) print "#define " byname[i] " " i > F1
	print "#define NIVF " max+1 > F1
	printf("#define IV_ERROR_MASK %.0fu\n", errmask) > F1
	printf("#define IV_WARNING_MASK %.0fu\n", warnmask) > F1

	print "/* File generated by gen_ivanalyzeflags.sh, do not edit by hand */" > F2
	print "char *iv_flag_messages[] = {" > F2
	print "\t\"All OK\"," > F2
	for (i=1;i<=max;i++) print "\t" message[i] "," > F2
	print "\tNULL" > F2
	print "};" > F2
	print "/* flag names (without the FLAG_ prefix), same order as the messages */" > F2
	print "char *iv_flag_names[] = {" > F2
	print "\t\"NOFLAG\"," > F2
	for (i=1;i<=max;i++) { n=byname[i]; sub(/^FLAG_/, "", n); print "\t\"" n "\"," > F2 }
	print "\tNULL" > F2
	print "};" > F2
	print "/* 1 for error flags, 0 for warnings */" > F2
	print "int iv_flag_is_error[] = {" > F2
	print "\t0," > F2
	for (i=1;i<=max;i++) print "\t" iserr[i] "," > F2
	print "};" > F2
}' "$TMP"

#!/bin/bash

# Generate error flags and messages
# to be used in conjunction with error.c and error.h
# searches the sources for commentlines following the pattern:
# // ERRORFLAG <FLAGNAME> "<message string>"
#
# it generates a macro by the name FLAGNAME and adds a string to the error string array
# the defines are in errorflags.h"
# the message array in "errormessages.h"
# the errorflags.h should be included in all sources that throw errors
# the  "errormessages.h" is a private include for the error.c
FILE1="ivanalyzeflags.h"
FILE2="ivanalyzemessages.h"
echo "/* File generated by gen_ivanalyzeflags.sh, do not edit by hand */" >  $FILE1
NIVF=1;
if [ -z "$1" ]
then
	echo gen_ivanalyzeflags.sh needs arguments!
	exit 1
fi
srcdir="$1"
shift
# first collect all error flags in one file
for s in $@
do
	echo Collecting warning flags from $s
	grep -Eo '//IVFLAGWARN.*' "$srcdir/$s" | uniq >>tmperrflags
done
NIVWARN=$(wc -l tmperrflags | awk '{print $1+1}')

for s in $@
do
	echo Collecting error flags from $s
	grep -Eo '//IVFLAGERR.*' "$srcdir/$s" | uniq >>tmperrflags
done
NIVF=$(wc -l tmperrflags | awk '{print $1+1}')

ERRO=1
ERRO=$((ERRO << (NIVWARN-1)))


# create the error flag defines
echo "#define FLAG_NOFLAG 0" >>$FILE1
awk '{print "#define",$2,NR}' tmperrflags>>$FILE1
echo "#define NIVF $NIVF" >>$FILE1
echo "#define NIVWARN $NIVWARN" >>$FILE1
echo "#define ERRTH $ERRO" >>$FILE1

	
	
echo "/* File generated by gen_ivanalyzeflags.sh, do not edit by hand */" >  $FILE2


echo "char *iv_flag_messages[] = {"  >>$FILE2
echo "	\"All OK\","  >>$FILE2
grep -Eo '//IVFLAG.*' tmperrflags|grep -Eo '".*"' |awk '{print "	"$0","}' >>$FILE2

echo "	NULL"  >>$FILE2
echo "};"  >>$FILE2

# flag names (without the FLAG_ prefix), same order as the messages
echo "char *iv_flag_names[] = {"  >>$FILE2
echo "	\"NOFLAG\","  >>$FILE2
awk '{sub(/^FLAG_/, "", $2); print "	\""$2"\","}' tmperrflags >>$FILE2
echo "	NULL"  >>$FILE2
echo "};"  >>$FILE2


rm tmperrflags
